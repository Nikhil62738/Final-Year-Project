/**
 * Lookup product by barcode from the curated catalog.
 * Also checks manufacturer prefixes if exact barcode not present.
 */
export function lookupIndianCatalogProduct(barcode) {
  const code = String(barcode || "").trim();
  if (!code) return null;

  // Direct match
  if (INDIAN_FOOD_CATALOG[code]) {
    return INDIAN_FOOD_CATALOG[code];
  }

  // Parle-G prefix match fallback (8901719)
  if (code.startsWith("8901719119") || code.startsWith("890171911") || code.startsWith("890171912") || code.startsWith("890171913")) {
    const base = INDIAN_FOOD_CATALOG["8901719119194"];
    return {
      ...base,
      code,
      product_name: "Parle-G Original Gluco Biscuits",
    };
  }

  return null;
}
